# Pergunta 1: Quem criou a linguagem Python e em que década ela foi lançada?
# Resposta: A linguagem Python foi criada pelo programador holandês Guido van Rossum no final da década de 1980 (com lançamento oficial em 1991).

# Pergunta 2: De onde vem o nome "Python"?
# Resposta: O nome foi inspirado no programa de comédia britânico "Monty Python's Flying Circus", do qual o criador da linguagem era fã, e não na cobra.

# Pergunta 3: Cite três áreas em que o Python é utilizado atualmente.
# Resposta: O Python é amplamente utilizado em Inteligência Artificial / Ciência de Dados, Desenvolvimento Web e Automação de Processos (scripts/testes).

# Pergunta 4: O que é uma IDE? Qual IDE estamos utilizando nesta UC?
# Resposta: Uma IDE (Ambiente de Desenvolvimento Integrado) é um programa que reúne ferramentas como editor de código, depurador e terminal para facilitar a programação. Nesta UC, estamos utilizando o VS Code (Visual Studio Code).

# Pergunta 5: Para que servem as extensões do VS Code? Cite a extensão que instalamos para trabalhar com Python.
# Resposta: As extensões servem para adicionar novas funcionalidades, suporte a linguagens e recursos extras ao editor. Para trabalhar com Python, instalamos a extensão oficial "Python" (desenvolvida pela Microsoft).

# Pergunta 6: O que é um comentário em Python e por que os programadores devem usar comentários?
# Resposta: Um comentário é uma linha de texto iniciada com o caractere # que é ignorada pelo interpretador. Programadores usam comentários para explicar a lógica do código, documentar o projeto e facilitar o entendimento do programa por outras pessoas ou no futuro.

# Pergunta 7: O que é uma variável? Dê um exemplo.
# Resposta: Uma variável é um espaço nomeado na memória do computador destinado a armazenar e manipular dados durante a execução do programa. Exemplo: idade = 25.

# Pergunta 8: Cite os quatro tipos primitivos estudados e dê um exemplo de valor de cada um.
# Resposta: Os quatro tipos primitivos são: int (inteiro, ex: 10), float (decimal, ex: 3.14), str (texto, ex: "Olá") e bool (lógico, ex: True).

# Pergunta 9: Qual é a diferença entre "10" e 10 em Python?
# Resposta: "10" (com aspas) é um valor do tipo texto (string) e não realiza cálculos matemáticos, enquanto 10 (sem aspas) é um valor do tipo número inteiro (int) pronto para operações matemáticas.

# Pergunta 10: O que a função input faz e qual é o tipo do valor que ela devolve?
# Resposta: A função input exibe uma mensagem na tela solicitando um dado ao usuário e aguarda a digitação. Ela sempre devolve um valor do tipo texto (string).

# Pergunta 11: Por que em alguns programas precisamos escrever int(input(...)) ou float(input(...))?
# Resposta: Como o input sempre retorna o valor digitado no formato de texto (string), precisamos usar int() ou float() para converter esse texto em um número antes de fazer cálculos numéricos.

# Pergunta 12: Por que o número 2,5 está escrito de forma errada para o Python? Como deve ser escrito?
# Resposta: O número 2,5 está incorreto porque o Python adota o padrão americano, que utiliza ponto para separar as casas decimais. A forma correta de escrever é 2.5.